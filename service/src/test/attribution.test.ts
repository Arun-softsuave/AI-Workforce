import "./helpers.js";
import test from "node:test";
import assert from "node:assert/strict";
import { attributionHits, stripAttribution, attributionInDiff } from "../core/attribution.js";

test("attribution is detected in all its usual forms", () => {
  for (const s of ["Generated with Claude Code", "Co-Authored-By: Claude <noreply@anthropic.com>", "Prepared by AI Workforce", "This code was written by an AI",
    "AI-generated helper", "🤖 Generated", "made with anthropic models", "written using ChatGPT"]) {
    assert.ok(attributionHits(s).length, `should flag: ${s}`);
  }
  for (const s of ["feat(buyer): validate input length KAN-42", "Add retry for the AI engine job queue", "Fix email validation", "ai_engine/domain/turn_types.py"]) {
    assert.equal(attributionHits(s).length, 0, `should NOT flag: ${s}`);
  }
});

test("outgoing text is cleaned: attribution lines dropped, normal text kept", () => {
  const body = "## Summary\nValidate buyer input length.\n\n🤖 Generated with Claude Code\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n_Prepared by AI Workforce._";
  const clean = stripAttribution(body);
  assert.equal(attributionHits(clean).length, 0);
  assert.match(clean, /Validate buyer input length/);
  assert.equal(stripAttribution("KAN-42: input guard (prepared by AI Workforce)"), "KAN-42: input guard");
});

test("added lines in the diff are checked; removed lines and the local .ai-workforce folder are ignored", () => {
  const diff = [
    "+++ b/app/guard.py", "+# Generated by Claude", "+def guard(text):", "-# old note written by AI",
    "+++ b/.ai-workforce/knowledge/standards.md", "+Maintained by AI Workforce",
  ].join("\n");
  const hits = attributionInDiff(diff);
  assert.deepEqual(hits.map((h) => h.file), ["app/guard.py"]);
});
